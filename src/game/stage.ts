export function getStageMap(stageIndex: number): number[][] {
  return stageMaps[Math.min(stageIndex, stageMaps.length - 1)];
}

export function getMapCols(stageIndex: number): number {
  return getStageMap(stageIndex)[0].length;
}

export function getMapRows(stageIndex: number): number {
  return getStageMap(stageIndex).length;
}

/** スタートセルの中心ピクセル座標を返す */
export function getStartPos(stageIndex: number, tileSize: number): { x: number; y: number } {
  const map = getStageMap(stageIndex);
  for (let row = 0; row < map.length; row++) {
    for (let col = 0; col < map[row].length; col++) {
      if (map[row][col] === CELL_START) {
        return { x: col * tileSize + tileSize / 2, y: row * tileSize + tileSize / 2 };
      }
    }
  }
  return { x: tileSize * 1.5, y: tileSize * 1.5 };
}

/** 敵配置セルからの初期位置リストを返す */
export function getEnemyStartPositions(stageIndex: number, tileSize: number): { x: number; y: number }[] {
  const map = getStageMap(stageIndex);
  const result: { x: number; y: number }[] = [];
  for (let row = 0; row < map.length; row++) {
    for (let col = 0; col < map[row].length; col++) {
      if (map[row][col] === CELL_ENEMY) {
        result.push({ x: col * tileSize + tileSize / 2, y: row * tileSize + tileSize / 2 });
      }
    }
  }
  return result;
}

/** (col, row) のセルタイプを返す */
export function getCellAt(stageIndex: number, col: number, row: number): number {
  const map = getStageMap(stageIndex);
  if (row < 0 || row >= map.length || col < 0 || col >= map[0].length) return CELL_WALL;
  return map[row][col];
}

/** 黄色敵の初期ピクセル座標リストを返す */
export function getYellowEnemyStartPositions(
  stageIndex: number,
  tileSize: number,
): { x: number; y: number }[] {
  const defs = stageYellowEnemies[Math.min(stageIndex, stageYellowEnemies.length - 1)] ?? [];
  return defs.map((p) => ({
    x: p.col * tileSize + tileSize / 2,
    y: p.row * tileSize + tileSize / 2,
  }));
}

/** ハートアイテムの初期ピクセル座標リストを返す */
export function getStageItemPositions(
  stageIndex: number,
  tileSize: number,
): { x: number; y: number }[] {
  const defs = stageHeartItems[Math.min(stageIndex, stageHeartItems.length - 1)] ?? [];
  return defs.map((p) => ({
    x: p.col * tileSize + tileSize / 2,
    y: p.row * tileSize + tileSize / 2,
  }));
}

/**
 * そのステージの敵 HP を返す
 * ステージ 1-4  → 1
 * ステージ 5-7  → 2
 * ステージ 8-10 → 3
 */
export function getEnemyHp(stageIndex: number): number {
  if (stageIndex >= 7) return 3;
  if (stageIndex >= 4) return 2;
  return 1;
}
