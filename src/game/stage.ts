/**
 * そのステージの赤/黄色敵 HP を返す
 * ステージ 1-5  → 1
 * ステージ 6-9  → 2
 * ステージ 10-14 → 3
 * ステージ 15-19 → 4
 * ステージ 20-30 → 5
 */
export function getEnemyHp(stageIndex: number): number {
  if (stageIndex >= 19) return 5;
  if (stageIndex >= 14) return 4;
  if (stageIndex >= 9)  return 3;
  if (stageIndex >= 5)  return 2;
  return 1;
}
